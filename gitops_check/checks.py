"""Each check returns (errors, warnings), lists of human-readable strings:
errors block the merge, warnings are for the reviewer.
"""
from __future__ import annotations

import fnmatch
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import yaml

from .config import Config, same_repo
from .kinds import is_cluster_scoped
from .render import App, Rendering, _sources

GENERATED_MARK = "# Generated by deploy-talos.py"
# Argo CD repository and cluster Secrets are declarative settings; only these
# keys (or these words in a cluster's config) make them credentials.
ARGOCD_SECRET_TYPES = {"repository", "repo-creds", "repository-write", "cluster"}
CREDENTIAL_KEYS = {"password", "sshPrivateKey", "tlsClientCertKey", "githubAppPrivateKey", "bearerToken",
                   "gcpServiceAccountKey", "awsSecretAccessKey"}
CREDENTIAL_WORDS = ("bearerToken", "password", "keyData", "awsAuthConfig", "execProviderConfig")


def rid(r: dict, default_ns: str = "") -> str:
    """A resource's identity: group/kind namespace/name. A namespaced resource
    without a namespace lands in its Application's destination namespace."""
    group = r.get("apiVersion", "").rpartition("/")[0]
    md = r.get("metadata", {})
    ns = md.get("namespace") or ("" if is_cluster_scoped(r) else default_ns)
    return f"{group + '/' if group else ''}{r.get('kind', '?')} {ns + '/' if ns else ''}{md.get('name', '?')}"


def dest_ns(a: App) -> str:
    """An Application's destination namespace ("" when it has none)."""
    return (a.spec.get("spec", {}).get("destination") or {}).get("namespace", "")


def render_errors(r: Rendering) -> tuple[list[str], list[str]]:
    errors = [f"{a.name}: {a.error}" for a in r.apps.values() if a.error]
    return errors + r.errors, list(r.warnings)


def duplicates(r: Rendering) -> tuple[list[str], list[str]]:
    owner: dict[str, str] = {}
    errors = []
    for a in r.apps.values():
        for res in a.resources:
            k = rid(res, dest_ns(a))
            if k in owner and owner[k] != a.name:
                errors.append(f"{k} is rendered by both {owner[k]} and {a.name}")
            owner.setdefault(k, a.name)
    return errors, []


def _is_credential(doc: dict) -> bool:
    labels = (doc.get("metadata") or {}).get("labels") or {}
    if labels.get("argocd.argoproj.io/secret-type") not in ARGOCD_SECRET_TYPES:
        return True
    values = {**(doc.get("data") or {}), **(doc.get("stringData") or {})}
    return bool(CREDENTIAL_KEYS & set(values)) or any(w in str(values.get("config", "")) for w in CREDENTIAL_WORDS)


def plaintext_secrets(tree: Path, cfg: Config) -> tuple[list[str], list[str]]:
    ignored = [(tree / i).resolve() for i in cfg.ignore]
    errors = []
    for f in sorted(tree.rglob("*.y*ml")):
        if ".git" in f.parts or any(x == f.parent.resolve() or x in f.resolve().parents for x in ignored):
            continue
        try:
            docs = [d for d in yaml.safe_load_all(f.read_text(errors="replace")) if isinstance(d, dict)]
        except yaml.YAMLError:
            continue
        rel = f.relative_to(tree)
        for d in docs:
            if d.get("kind") == "Secret" and (d.get("data") or d.get("stringData")) and "sops" not in d \
                    and _is_credential(d):
                errors.append(f"{rel}: Secret {d.get('metadata', {}).get('name', '?')} has values in clear "
                              f"(encrypt it with sops and list it in a ksops generator)")
            if f.name in ("kustomization.yaml", "kustomization.yml") and d.get("secretGenerator"):
                errors.append(f"{rel}: secretGenerator puts Secret values in Git in clear (use a SOPS-encrypted "
                              f"Secret and ksops)")
    return errors, []


def schemas(r: Rendering, kubeconform: str = "kubeconform") -> tuple[list[str], list[str]]:
    if not shutil.which(kubeconform):
        return [], [f"{kubeconform} not found: schemas not checked"]
    docs, owners = [], []
    for a in r.apps.values():
        for res in a.resources:
            if res.get("kind") == "Secret":       # values masked by Argo CD: not valid base64
                res = {k: v for k, v in res.items() if k not in ("data", "stringData")}
            docs.append(res)
            owners.append(a.name)
    if not docs:
        return [], []
    cache = Path(os.environ.get("KUBECONFORM_CACHE", "/tmp/kubeconform-cache"))
    cache.mkdir(parents=True, exist_ok=True)
    # One worker and every result (-verbose): results come in input order, so
    # each one maps back to the Application that rendered the resource.
    p = subprocess.run(
        [kubeconform, "-output", "json", "-verbose", "-n", "1", "-ignore-missing-schemas", "-cache", str(cache),
         "-schema-location", "default",
         "-schema-location",
         "https://raw.githubusercontent.com/datreeio/CRDs-catalog/main/{{.Group}}/{{.ResourceKind}}_{{.ResourceAPIVersion}}.json",
         "-"],
        input=yaml.safe_dump_all(docs), capture_output=True, text=True, timeout=600, check=False)
    try:
        out = json.loads(p.stdout)
    except ValueError:
        return [], [f"kubeconform: unreadable output: {(p.stderr or p.stdout)[:300]}"]
    results = out.get("resources") or []
    if len(results) != len(docs):
        owners = ["?"] * len(results)
    errors, warnings, skipped = [], [], 0
    for res, owner in zip(results, owners, strict=False):
        if res["status"] in ("statusInvalid", "statusError"):
            msg = re.sub(r"^problem validating schema\..* - at ", "at ", res.get("msg", ""))
            errors.append(f"{owner}: {res.get('kind')} {res.get('name')}: {msg}")
        elif res["status"] == "statusSkipped":
            skipped += 1
    if skipped:
        warnings.append(f"{skipped} resource(s) without a known schema: not validated")
    return errors, warnings


def _kustomize_refs(d: Path, root: Path, seen: set[Path]) -> None:
    if d in seen or not d.is_dir():
        return
    seen.add(d)
    for name in ("kustomization.yaml", "kustomization.yml", "Kustomization"):
        k = d / name
        if k.is_file():
            break
    else:
        return
    try:
        doc = yaml.safe_load(k.read_text()) or {}
    except yaml.YAMLError:
        return
    refs: list[str] = []
    for key in ("resources", "bases", "components", "generators", "transformers", "crds"):
        refs += [x for x in doc.get(key) or [] if isinstance(x, str)]
    for p in doc.get("patches") or []:
        if isinstance(p, dict) and p.get("path"):
            refs.append(p["path"])
    for g in (doc.get("configMapGenerator") or []) + (doc.get("secretGenerator") or []):
        refs += [f.split("=", 1)[-1] for f in g.get("files") or []]
    for ref in refs:
        if "://" in ref or ref.startswith("github.com/"):
            continue
        t = (d / ref).resolve()
        if root.resolve() not in t.parents and t != root.resolve():
            continue
        if t.is_dir():
            _kustomize_refs(t, root, seen)
        else:
            seen.add(t.parent)


def unreached(r: Rendering, cfg: Config, tree: Path, git_globs: list[str]) -> tuple[list[str], list[str]]:
    reached: set[Path] = set()
    recursive: set[Path] = set()
    for e in cfg.entrypoints:
        _kustomize_refs((tree / e.path).resolve(), tree, reached)
        if e.recurse:
            recursive.add((tree / e.path).resolve())
    for a in r.apps.values():
        for s in _sources(a.spec.get("spec", {})):
            if same_repo(s.get("repoURL", ""), cfg.repo_url) and s.get("path") is not None:
                p = (tree / s["path"]).resolve()
                _kustomize_refs(p, tree, reached)
                reached.add(p)
                if (s.get("directory") or {}).get("recurse") or (p / "Chart.yaml").is_file():
                    recursive.add(p)
                # Components Argo CD adds to the kustomization (relative to it).
                for c in (s.get("kustomize") or {}).get("components") or []:
                    cp = (p / c).resolve()
                    _kustomize_refs(cp, tree, reached)
                    reached.add(cp)
    for g in git_globs:
        for m in tree.glob(g):
            reached.add((m if m.is_dir() else m.parent).resolve())
    ignored = [(tree / i).resolve() for i in cfg.ignore]
    errors = []
    for d in sorted({f.parent.resolve() for f in tree.rglob("*.y*ml")
                     if not f.name.startswith(".") and ".git" not in f.parts}):
        if d == tree.resolve() or d in reached or any(x == d or x in d.parents for x in ignored + list(recursive)):
            continue
        errors.append(f"{d.relative_to(tree.resolve())}/ has manifests that no entry point reaches "
                      f"(a wrong path in an Application? else list it under 'ignore' in .gitops-check.yaml)")
    return errors, []


def git_generator_globs(r: Rendering, cfg: Config, appsets: list[dict]) -> list[str]:
    globs = []

    def walk(gens):
        for g in gens or []:
            git = g.get("git")
            if git and same_repo(git.get("repoURL", ""), cfg.repo_url):
                globs.extend(re.sub(r"\{\{.*?\}\}", "*", x["path"])
                             for x in (git.get("directories") or []) + (git.get("files") or [])
                             if not x.get("exclude"))
            for n in ("matrix", "merge"):
                if n in g:
                    walk(g[n].get("generators"))
    for s in appsets:
        walk(s.get("spec", {}).get("generators"))
    return globs


def generated_edits(tree: Path, changed_files: list[str]) -> tuple[list[str], list[str]]:
    warnings = []
    for f in changed_files:
        p = tree / f
        if p.is_file() and p.read_text(errors="replace").startswith(GENERATED_MARK):
            warnings.append(f"{f} is generated by deploy-talos.py: change the cluster file and run it, "
                            f"or this edit is overwritten")
    return [], warnings


def _globs(value: str, patterns: list[str]) -> bool:
    """Argo CD's project matching: allowed when a pattern matches and no
    negated one ("!pattern") does."""
    deny = [p[1:] for p in patterns if p.startswith("!")]
    allow = [p for p in patterns if not p.startswith("!")]
    return any(fnmatch.fnmatchcase(value, p) for p in allow) and not any(fnmatch.fnmatchcase(value, p) for p in deny)


def _dest_ok(server: str, name: str, ns: str, dests: list[dict]) -> bool:
    def cluster(d: dict) -> bool:
        return (bool(d.get("server")) and fnmatch.fnmatchcase(server, d["server"])) or \
               (bool(d.get("name")) and fnmatch.fnmatchcase(name, d["name"]))
    nss = [str(d.get("namespace", "")) for d in dests if cluster(d)]
    return _globs(ns, nss)


def _kind_ok(group: str, kind: str, lst: list[dict]) -> bool:
    return any(fnmatch.fnmatchcase(group, str(e.get("group", ""))) and fnmatch.fnmatchcase(kind, str(e.get("kind", "")))
               for e in lst)


def projects(r: Rendering, cfg: Config) -> tuple[list[str], list[str]]:
    projs = {}
    for a in r.apps.values():
        for res in a.resources:
            md = res.get("metadata") or {}
            if res.get("kind") == "AppProject" and res.get("apiVersion", "").startswith("argoproj.io/") and \
                    (md.get("namespace") or dest_ns(a)) == "argocd":
                projs[md.get("name", "")] = res.get("spec") or {}
    if not projs:
        return [], []
    errors = []
    undeployed = {e.name for e in cfg.entrypoints if not e.deployed}
    for a in r.apps.values():
        if "/" in a.name or a.parent is None or a.entrypoint in undeployed:
            continue
        if a.project not in projs:
            # A 'default' project not in Git is Argo CD's own, which permits everything.
            if a.project != "default":
                errors.append(f"{a.name}: project {a.project} doesn't exist")
            continue
        p = projs[a.project]
        spec = a.spec.get("spec", {})
        for s in _sources(spec):
            if not _globs(s.get("repoURL", ""), [str(x) for x in p.get("sourceRepos") or []]):
                errors.append(f"{a.name}: source {s.get('repoURL')} is not permitted in project {a.project}")
        d = spec.get("destination") or {}
        server, name = d.get("server", ""), d.get("name", "")
        dests = p.get("destinations") or []
        if not _dest_ok(server, name, d.get("namespace", ""), dests):
            errors.append(f"{a.name}: destination namespace {d.get('namespace', '')!r} is not permitted in project {a.project}")
        refused: dict[str, list[str]] = {}
        for res in a.resources:
            group, kind = res.get("apiVersion", "").rpartition("/")[0], res.get("kind", "")
            if is_cluster_scoped(res):
                if not _kind_ok(group, kind, p.get("clusterResourceWhitelist") or []) or \
                        _kind_ok(group, kind, p.get("clusterResourceBlacklist") or []):
                    refused.setdefault("cluster-scoped kind", []).append(rid(res))
                continue
            wl = p.get("namespaceResourceWhitelist")
            if (wl is not None and not _kind_ok(group, kind, wl)) or \
                    _kind_ok(group, kind, p.get("namespaceResourceBlacklist") or []):
                refused.setdefault("kind", []).append(rid(res, dest_ns(a)))
            ns = (res.get("metadata") or {}).get("namespace") or d.get("namespace", "")
            if ns and not _dest_ok(server, name, ns, dests):
                refused.setdefault("namespace", []).append(rid(res, dest_ns(a)))
        for why, ids in sorted(refused.items()):
            more = f" (+{len(ids) - 3} more)" if len(ids) > 3 else ""
            errors.append(f"{a.name}: {why} not permitted in project {a.project}: {', '.join(ids[:3])}{more}")
    return errors, []
